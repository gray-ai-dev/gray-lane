import { sha256 } from "@noble/hashes/sha2";
import { bytesToLowerHex, lowerHexBytes, utf8Bytes } from "./digest.ts";

/**
 * The two digests a relay-stack receipt (docs/confidential-lane-supply-implementation.md S26) defines
 * on top of what Gray's egress reports in its feed (S17).
 *
 * **`events_sha256`: a hash chain over S19 event digests.** Egress digests each SSE event the vendor
 * sends (S19: `SHA-256(type || LF || canon(data))`, lower hex); the entry digests each event it hands
 * to the client the same way. A receipt carries one value per stream:
 *
 *     h_0 = SHA-256(TAG || 0x00)
 *     h_i = SHA-256(TAG || 0x01 || h_{i-1} || d_i)      i = 1 .. k
 *     events_sha256 = lower hex of h_k
 *
 * `TAG` is the 20 ASCII bytes `gray-stack-events/v1`, `h_{i-1}` the previous 32-byte value and `d_i`
 * the i-th event digest as its 32 raw bytes (the S19 hex decoded). A stream of no events has
 * `h_0`. Domain separation: every input starts with the tag, which no other Gray hash uses, so a
 * chain value is never the SHA-256 of another construction's input that does not begin with it; the
 * initial value (21 bytes, marker 0x00) and a step (85 bytes, marker 0x01) are inputs of distinct
 * form, so an empty chain is never a step. The chain is incremental, so the entry keeps 32 bytes per
 * stream rather than every digest. `test/fixtures/aci-vectors.json` (`gray.stack_events_chains`) pins
 * it, generated by `gen-gray-vectors.mjs` with `node:crypto` alone.
 *
 * **`headers_sha256` of a response head.** The same line form egress uses for the request headers
 * it forwards (`deploy/tee/egress/stack_relay.go` `headersSHA256`): one `name:value\n` line per value,
 * names in lower case and sorted (byte order), the values of one name in the order given. The entry
 * computes it over the allowlisted response headers of the feed's `response` record (S17), whose
 * repeated values egress already joined with `, `.
 */

/** The chain's domain tag (ASCII). */
export const STACK_EVENTS_CHAIN_TAG = "gray-stack-events/v1";

const TAG = utf8Bytes(STACK_EVENTS_CHAIN_TAG);
const INITIAL = 0x00;
const STEP = 0x01;

/** `h_0`, the value of a stream that carried no event. */
export function stackEventsChainStart(): Uint8Array {
  const input = new Uint8Array(TAG.length + 1);
  input.set(TAG, 0);
  input[TAG.length] = INITIAL;
  return sha256(input);
}

/** One step: `SHA-256(TAG || 0x01 || previous || digest)`, both 32 raw bytes. */
export function stackEventsChainStep(previous: Uint8Array, digest: Uint8Array): Uint8Array {
  if (previous.length !== 32 || digest.length !== 32) throw new Error("a chain step takes two 32-byte values");
  const input = new Uint8Array(TAG.length + 1 + 64);
  input.set(TAG, 0);
  input[TAG.length] = STEP;
  input.set(previous, TAG.length + 1);
  input.set(digest, TAG.length + 33);
  return sha256(input);
}

/** The incremental form: push each released event's S19 digest, read the value at any point. */
export class StackEventsChain {
  #value: Uint8Array = stackEventsChainStart();
  #count = 0;

  /** Add one event's S19 digest (64 lower hex). Throws on any other text. */
  push(digestHex: string): void {
    this.#value = stackEventsChainStep(this.#value, eventDigestBytes(digestHex));
    this.#count += 1;
  }

  /** The chain value so far, lower hex: the `events_sha256` of the events pushed. */
  hex(): string {
    return bytesToLowerHex(this.#value);
  }

  /** How many events were pushed. */
  count(): number {
    return this.#count;
  }
}

/** `events_sha256` of a whole list of S19 digests (lower hex in, lower hex out). */
export function stackEventsSha256(digests: readonly string[]): string {
  const chain = new StackEventsChain();
  for (const digest of digests) chain.push(digest);
  return chain.hex();
}

/**
 * `headers_sha256` of a header list: `name:value\n` lines, names lower-cased and sorted, the values
 * of one name in the order given. Throws on a name that is empty or holds `:`, CR or LF, and on a
 * value that holds CR or LF: such a header is not HTTP, and its lines would not be unambiguous.
 */
export function stackHeadersSha256(headers: readonly (readonly [string, string])[]): string {
  const lines = headers.map(([name, value], index) => {
    if (name === "" || /[:\r\n]/.test(name)) throw new Error(`header ${index} has no valid name`);
    if (/[\r\n]/.test(value)) throw new Error(`header ${index} has a value with a line break`);
    return { name: name.toLowerCase(), value, index };
  });
  // Byte order of the lower-cased names; the original index keeps the given order within a name.
  lines.sort((left, right) => compareBytes(utf8Bytes(left.name), utf8Bytes(right.name)) || left.index - right.index);
  return bytesToLowerHex(sha256(utf8Bytes(lines.map((line) => `${line.name}:${line.value}\n`).join(""))));
}

function eventDigestBytes(digestHex: string): Uint8Array {
  const bytes = typeof digestHex === "string" && digestHex.length === 64 ? lowerHexBytes(digestHex) : null;
  if (bytes === null) throw new Error("an S19 event digest is 64 lower-case hex digits");
  return bytes;
}

function compareBytes(left: Uint8Array, right: Uint8Array): number {
  const length = Math.min(left.length, right.length);
  for (let index = 0; index < length; index += 1) {
    const difference = (left[index] as number) - (right[index] as number);
    if (difference !== 0) return difference;
  }
  return left.length - right.length;
}
