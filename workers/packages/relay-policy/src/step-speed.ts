/**
 * The policy step's speed (F2 D128, D128'): the two numbers the confidential lane's policy step budget
 * is computed from, how they are derived from timed runs, and the modules that are timed.
 *
 *     T(input) = min(ceil(fuel(input) / fuelPerMs) + overheadMs, LANE_POLICY_STEP_MS)
 *
 * (the lane raises the cap at boot when its calibration would make it bind at the largest input, F2 D130)
 *
 * - `overheadMs` is the fixed cost around any module: building the input, a fresh instance, writing
 *   the input, reading and validating the answer. The trivial module (`allow`, which answers at once)
 *   measures it.
 * - `fuelPerMs` is the interpreter's fuel throughput on a module that spends its whole budget. Three
 *   burn shapes measure it (`burn-branch`, `burn-memory`, `burn-call`); the slowest one bounds it.
 *   Which shape is slowest depends on the CPU and the runtime: on the build box in workerd it was
 *   `burn-branch` (F2 D128' measurement, 2026-10-22: 188,401 fuel per ms in workerd 1.20261006.1 on
 *   an AMD Ryzen 9 9950X3D), while a loaded Mac in Node had `burn-call` about twice as slow as
 *   `burn-branch` (the D128 review's runs; an order, not a rate to cite). So every shape is timed wherever the rate is measured.
 *
 * Two callers derive them, from the same shipped modules:
 *
 * - the benchmark (`bench/policy-step.ts`) times every shape at every size up to the 4 MiB cap on the
 *   build box, and {@link deriveStepSpeed} gives the configured values: the largest trivial p99
 *   rounded up, and the smallest `fuel / (p99 - overheadMs)` rounded down. At the cap a run is
 *   hundreds of ms, so the clock's resolution does not matter there.
 * - the lane's boot calibration ({@link measureStepSpeed} over {@link sandboxStepSpeedRunner}) times
 *   the same shapes on a small body on the machine it serves from, where one clock tick is a large
 *   share of a run, so its derivation is the conservative one described there: a group of runs per
 *   reading, one tick added to every reading, nothing subtracted from a burn reading, and the
 *   trivial module on the largest body.
 *
 * The modules ship in this package (`step-speed-modules.ts`, generated by `test/fixtures/build.mjs`
 * from the same WAT as the test fixtures), so a Worker reads no file.
 *
 * Pure code like the rest of the package: the clock is the caller's.
 */
import type { LaneProtocol } from "@gray/lane";
import type { PolicyLimitOverrides } from "./limits.ts";
import { policyRunFuel, preparePolicy, runPolicy, type PreparedPolicy, type PolicyRequest } from "./sandbox.ts";
import { STEP_SPEED_MODULE_BASE64 } from "./step-speed-modules.ts";

/** The module that answers at once: the fixed cost around any module. */
export const STEP_TRIVIAL_MODULE = "allow";
/** The modules that spend their whole budget, one per shape the interpreter may be slowest on (F2 D128'). */
export const STEP_BURN_MODULES = ["burn-branch", "burn-memory", "burn-call"] as const;
/** One of the burn shapes. */
export type StepBurnModule = (typeof STEP_BURN_MODULES)[number];
/** The modules this package ships for measuring the step. */
export type StepSpeedModule = keyof typeof STEP_SPEED_MODULE_BASE64;

/** The protocol and model every timed run uses: one fixed input per size, so two runs run the same instructions. */
export const STEP_SPEED_PROTOCOL: LaneProtocol = "anthropic_messages";
export const STEP_SPEED_MODEL = "claude-sonnet-4-5";

/** The two settings, as one run measured them. */
export interface StepSpeed {
  /** LANE_POLICY_FUEL_PER_MS: wasmi fuel per ms on the slowest shape timed, rounded down, at least 1. */
  readonly fuelPerMs: number;
  /** LANE_POLICY_OVERHEAD_MS: the largest trivial p99 in ms, rounded up. */
  readonly overheadMs: number;
}

/** A measurement that cannot give the two settings: a module answered something else, or the clock saw nothing. */
export class StepSpeedError extends Error {
  override readonly name = "StepSpeedError";
}

/** The bytes of one of the shipped measuring modules, as a relay would upload them. */
export function stepSpeedModule(name: StepSpeedModule): Uint8Array {
  const binary = atob(STEP_SPEED_MODULE_BASE64[name]);
  const bytes = new Uint8Array(binary.length);
  for (let index = 0; index < binary.length; index += 1) bytes[index] = binary.charCodeAt(index);
  return bytes;
}

/**
 * A request body of `bytes` bytes (at least 88): an Anthropic message whose one user turn is `a`s. The
 * benchmark's cells and the lane's calibration use it, so the same size is the same input in both.
 */
export function stepSpeedBody(bytes: number): Uint8Array {
  const head = new TextEncoder().encode('{"model":"claude-sonnet-4-5","max_tokens":16,"messages":[{"role":"user","content":"');
  const tail = new TextEncoder().encode('"}]}');
  const body = new Uint8Array(bytes);
  body.set(head, 0);
  body.fill(0x61, head.length, bytes - tail.length);
  body.set(tail, bytes - tail.length);
  return body;
}

/** The p-th percentile by nearest rank (p in 0..100) of a non-empty list. Of 50 samples, p99 is the largest. */
export function percentile(values: readonly number[], p: number): number {
  if (values.length === 0) throw new StepSpeedError("no values to take a percentile of");
  const sorted = [...values].sort((left, right) => left - right);
  const rank = Math.max(1, Math.ceil((p / 100) * sorted.length));
  return sorted[rank - 1] as number;
}

/**
 * The two settings from timed cells: `overheadMs` = ceil(largest trivial p99); `fuelPerMs` =
 * floor(smallest `fuel / (burn p99 - overheadMs)`), at least 1. A burn cell at or under the overhead
 * bounds nothing (the overhead alone covers it); when every one is, the clock could not see the runs
 * and there is no throughput to give — a {@link StepSpeedError}, never a guess.
 */
export function deriveStepSpeed(trivialP99Ms: readonly number[], burn: readonly { readonly fuel: bigint; readonly p99Ms: number }[]): StepSpeed {
  if (trivialP99Ms.length === 0) throw new StepSpeedError("no trivial cell was timed");
  for (const ms of trivialP99Ms) if (!Number.isFinite(ms) || ms < 0) throw new StepSpeedError("a trivial cell's time is not a non-negative number");
  const overheadMs = Math.ceil(Math.max(...trivialP99Ms));
  let fuelPerMs = Number.POSITIVE_INFINITY;
  for (const cell of burn) {
    if (!Number.isFinite(cell.p99Ms)) throw new StepSpeedError("a burn cell's time is not a number");
    const runMs = cell.p99Ms - overheadMs;
    if (runMs > 0) fuelPerMs = Math.min(fuelPerMs, Number(cell.fuel) / runMs);
  }
  if (!Number.isFinite(fuelPerMs)) throw new StepSpeedError("no burn cell took longer than the overhead: the clock cannot see the runs");
  return { overheadMs, fuelPerMs: Math.max(1, Math.floor(fuelPerMs)) };
}

/** What a boot calibration runs: the trivial module on the overhead body, and each burn shape on the burn body. */
export interface StepSpeedRunner {
  /** The fuel every burn run is given (`policyRunFuel` of the burn body). */
  readonly burnFuel: bigint;
  /** One run of `allow`; a {@link StepSpeedError} unless it allowed. */
  trivial(): void;
  /** One run of a burn shape; a {@link StepSpeedError} unless it ran out of fuel. */
  burn(module: StepBurnModule): void;
}

/** The two body sizes of a calibration. */
export interface StepSpeedSizes {
  /** The body every burn run gets (the throughput's input). */
  readonly burnBytes: number;
  /** The body every trivial run gets: the largest a module is given, so the overhead covers its copy. */
  readonly trivialBytes: number;
}

function prepareShipped(name: StepSpeedModule, limits: PolicyLimitOverrides | undefined): PreparedPolicy {
  const prepared = preparePolicy(
    { relayId: "step-speed", version: 1n, moduleBytes: stepSpeedModule(name), templates: [] },
    limits === undefined ? {} : { limits },
  );
  if (!prepared.ok) throw new StepSpeedError(`the sandbox refused the ${name} module: ${prepared.code}`);
  return prepared.policy;
}

function speedRequest(bytes: number): PolicyRequest {
  return { protocol: STEP_SPEED_PROTOCOL, model: STEP_SPEED_MODEL, body: stepSpeedBody(bytes) };
}

/**
 * The real sandbox's runs of the shipped modules ({@link stepSpeedBody} bodies of the two sizes),
 * prepared with `limits` — the host's own, so a burn spends exactly the budget the host gives that
 * input. Needs the interpreter (`initInterpreter`, or the `workerd` entry).
 */
export function sandboxStepSpeedRunner(sizes: StepSpeedSizes, limits?: PolicyLimitOverrides): StepSpeedRunner {
  const trivialPolicy = prepareShipped(STEP_TRIVIAL_MODULE, limits);
  const burnPolicies = new Map<StepBurnModule, PreparedPolicy>(STEP_BURN_MODULES.map((name) => [name, prepareShipped(name, limits)]));
  const trivialRequest = speedRequest(sizes.trivialBytes);
  const burnRequest = speedRequest(sizes.burnBytes);
  // Every shape is prepared under the same limits, so each is given the same budget for the same body.
  const budgets = new Set([...burnPolicies.values()].map((policy) => policyRunFuel(policy, burnRequest)));
  const [burnFuel] = [...budgets];
  if (budgets.size !== 1 || burnFuel === undefined || burnFuel === null) throw new StepSpeedError(`the sandbox gives a ${sizes.burnBytes}-byte body no single fuel budget`);
  return {
    burnFuel,
    trivial() {
      const result = runPolicy(trivialPolicy, trivialRequest);
      if (result.cause !== null || result.outcome.decision !== "allow") throw new StepSpeedError(`${STEP_TRIVIAL_MODULE} answered ${result.cause ?? result.outcome.decision}, not allow`);
    },
    burn(module) {
      const policy = burnPolicies.get(module);
      if (policy === undefined) throw new StepSpeedError(`${module} is not a shipped burn shape`);
      const result = runPolicy(policy, burnRequest);
      if (result.cause !== "out_of_fuel") throw new StepSpeedError(`${module} answered ${result.cause ?? result.outcome.decision}, not out_of_fuel`);
    },
  };
}

/** How {@link measureStepSpeed} times the runner. */
export interface StepSpeedTiming {
  /** Timed groups of burn runs per shape. */
  readonly groups: number;
  /** Burn runs in one timed group: the clock is read before the group's first run and after its last. */
  readonly groupRuns: number;
  /** Untimed runs of each module before its timed ones. */
  readonly warmup: number;
  /** The clock's resolution in ms: a reading may be this much short of the time it spans. */
  readonly tickMs: number;
  /** The clock, in ms. */
  readonly clock: () => number;
}

/** One burn shape's reading. */
export interface StepBurnReading {
  readonly module: StepBurnModule;
  /** The longest timed group, in ms. */
  readonly slowestGroupMs: number;
  /** That group's fuel / (its time + one tick), rounded down: the shape's rate. */
  readonly fuelPerMs: number;
}

/** What one calibration saw, and the settings it derives. */
export interface StepSpeedMeasurement extends StepSpeed {
  /** The longest single trivial run, in ms. */
  readonly trivialMaxMs: number;
  readonly burnFuel: bigint;
  readonly burns: readonly StepBurnReading[];
  readonly groups: number;
  readonly groupRuns: number;
  readonly tickMs: number;
}

/**
 * The boot calibration's measurement (F2 D128'(c)), conservative where the benchmark's derivation is
 * exact only at the benchmark's sizes:
 *
 * - `overheadMs` = ceil(longest of `groups * groupRuns` single trivial runs + one tick), the trivial
 *   module on the largest body, so it covers the input copy at the cap; the tick because a reading
 *   can be up to one tick short of the run it spans.
 * - `fuelPerMs` = floor(min over every burn shape and every timed group of
 *   `groupRuns * burnFuel / (group time + one tick)`), at least 1. A group, not a single run, is timed
 *   so that one tick is a small share of the reading at a small input; nothing is subtracted from the
 *   reading (the burn runs' own fixed cost stays in it), so the rate can only read slow.
 *
 * Every run is synchronous and the clock is read around it (no timer in between: in workerd
 * 1.20261006.1 the clock advances during a synchronous run in 1 ms steps, measured 2026-10-22). A
 * group the clock did not see advance, a run that answered something else, or a bad parameter is a
 * {@link StepSpeedError}, never a guess.
 */
export function measureStepSpeed(runner: StepSpeedRunner, timing: StepSpeedTiming): StepSpeedMeasurement {
  if (!Number.isInteger(timing.groups) || timing.groups < 1) throw new StepSpeedError("groups is a positive integer");
  if (!Number.isInteger(timing.groupRuns) || timing.groupRuns < 1) throw new StepSpeedError("groupRuns is a positive integer");
  if (!Number.isInteger(timing.warmup) || timing.warmup < 0) throw new StepSpeedError("warmup is a non-negative integer");
  if (!Number.isFinite(timing.tickMs) || timing.tickMs <= 0) throw new StepSpeedError("tickMs is a positive number");
  const elapsed = (started: number, what: string): number => {
    const ms = timing.clock() - started;
    if (!Number.isFinite(ms) || ms < 0) throw new StepSpeedError(`the clock read ${String(ms)} ms across ${what}`);
    return ms;
  };

  for (let index = 0; index < timing.warmup; index += 1) runner.trivial();
  let trivialMaxMs = 0;
  for (let index = 0; index < timing.groups * timing.groupRuns; index += 1) {
    const started = timing.clock();
    runner.trivial();
    trivialMaxMs = Math.max(trivialMaxMs, elapsed(started, `a ${STEP_TRIVIAL_MODULE} run`));
  }
  const overheadMs = Math.ceil(trivialMaxMs + timing.tickMs);

  const groupFuel = Number(runner.burnFuel) * timing.groupRuns;
  const burns: StepBurnReading[] = [];
  for (const module of STEP_BURN_MODULES) {
    for (let index = 0; index < timing.warmup; index += 1) runner.burn(module);
    let slowestGroupMs = 0;
    for (let group = 0; group < timing.groups; group += 1) {
      const started = timing.clock();
      for (let index = 0; index < timing.groupRuns; index += 1) runner.burn(module);
      const ms = elapsed(started, `a group of ${module} runs`);
      if (ms <= 0) throw new StepSpeedError(`the clock did not advance across ${timing.groupRuns} ${module} runs: it cannot see the runs`);
      slowestGroupMs = Math.max(slowestGroupMs, ms);
    }
    burns.push({ module, slowestGroupMs, fuelPerMs: Math.max(1, Math.floor(groupFuel / (slowestGroupMs + timing.tickMs))) });
  }
  const fuelPerMs = Math.min(...burns.map((burn) => burn.fuelPerMs));
  return { overheadMs, fuelPerMs, trivialMaxMs, burnFuel: runner.burnFuel, burns, groups: timing.groups, groupRuns: timing.groupRuns, tickMs: timing.tickMs };
}
